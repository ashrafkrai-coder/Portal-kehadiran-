-- 3) RLS (terbuka untuk kegunaan dalaman; tambah Supabase Auth untuk production)
alter table staff enable row level security;
alter table kehadiran enable row level security;
alter table tetapan enable row level security;
create policy "staff_all" on staff for all using (true) with check (true);
create policy "kehadiran_all" on kehadiran for all using (true) with check (true);
create policy "tetapan_all" on tetapan for all using (true) with check (true);

-- 4) REALTIME (sync masa-nyata antara peranti)
alter publication supabase_realtime add table staff, kehadiran, tetapan;