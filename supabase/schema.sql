-- 1) TABLES
create table staff (
  id text primary key,
  nama text not null,
  jawatan text not null,
  pin text default '1234',
  img text
);

create table kehadiran (
  id bigint generated by default as identity primary key,
  staff_id text,
  nama text,
  jawatan text,
  tarikh text,
  masa_in text,
  masa_out text,
  open boolean default true,
  kaedah text,
  gps text,
  status_out text,
  waktu text,
  ts bigint unique
);

create table tetapan (
  id int primary key default 1,
  data jsonb not null default '{}'
);

